<p>
This keyboard layout is designed for typing the Numanggang language.
</p>

<h2>On a computer</h2>
<p>
Type the ; key to get the "ŋ" character.
Type the ; key again to get the ";" character.
Type the ; key a third time to get "ŋŋ".
</p>
<p>
Type the | key to get the "Ŋ" character.
Type the | key again to get the "|" character.
Type the | key a third time to get "ŊŊ".
</p>

<h2>On a phone</h2>
<p>
The phone keyboard has its own "ŋ" key, at the right end of the middle row next to L.
Press Shift first to get "Ŋ".
</p>
<p>
For ";" or ":", press and hold the . key. The "|" key is on the 123 layer.
</p>
<p>
If you don't see the "ŋ" key, Keyman is still using a different keyboard.
Press and hold the globe key on the Keyman keyboard, then choose Numanggang.
</p>

