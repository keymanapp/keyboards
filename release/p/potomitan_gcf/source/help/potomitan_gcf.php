<p>
  AnnouMaké (« Écrivons ! ») permet d'écrire le créole guadeloupéen avec les bons caractères,
  selon la graphie du GEREC. C'est un clavier AZERTY : seules deux touches changent.
</p>

<h2>Ce qui change par rapport à l'AZERTY</h2>

<img src="annoumake.png" style="max-width:100%; height:auto; border:1px solid #ccc; border-radius:8px" alt="Le clavier AnnouMaké affiché à l'écran : Q donne k, X donne ò">

<ul>
  <li>La touche <kbd>Q</kbd> donne <b>k</b>.</li>
  <li>La touche <kbd>X</kbd> donne <b>ò</b> (avec Maj : <b>Ò</b>).</li>
  <li><b>é</b>, <b>è</b>, <b>ç</b> et <b>à</b> restent à leur place habituelle, sur les touches 2, 7, 9 et 0.</li>
  <li>Pour les capitales accentuées <b>É È Ç À</b>, activez le verrouillage des majuscules
      (<kbd>Verr. Maj</kbd>) : la touche Maj, elle, donne les chiffres.</li>
  <li>L'accent circonflexe et le tréma fonctionnent comme d'habitude.</li>
  <li>Il n'y a ni <b>q</b> ni <b>x</b>, qui n'existent pas en créole guadeloupéen.
      Pour écrire en français, revenez à votre clavier habituel.</li>
</ul>

<h2>Passer d'un clavier à l'autre</h2>

<ul>
  <li><b>Windows</b> : touches <kbd>Windows</kbd> + <kbd>Espace</kbd>, puis choisissez AnnouMaké.
      Si AnnouMaké n'apparaît pas juste après l'installation, <b>redémarrez l'ordinateur</b>.</li>
  <li><b>Mac</b> : ajoutez d'abord Keyman dans <i>Réglages Système → Clavier → Méthodes de saisie</i>,
      puis choisissez AnnouMaké dans le menu de saisie, en haut à droite de l'écran.</li>
</ul>

<h2>Voir le clavier à l'écran</h2>

<p>
  Pas besoin d'apprendre les touches par cœur : un clavier visuel affiche ce que donne chaque touche.
</p>

<ul>
  <li><b>Windows</b> : ouvrez une fois la configuration de Keyman (icône Keyman, près de l'horloge), puis
      <i>Paramètres → Clavier virtuel</i>, et cochez <i>Toujours afficher le clavier visuel</i>.
      Le clavier à l'écran s'affiche ensuite dès que vous choisissez AnnouMaké.</li>
  <li><b>Mac</b> : AnnouMaké étant choisi, ouvrez le menu de saisie, en haut à droite de l'écran,
      puis cliquez sur <i>On-Screen Keyboard</i> (le clavier à l'écran ; les menus de Keyman sont en anglais).</li>
</ul>

<p>
  Ne regardez que les gros caractères : les petites lettres grises dans le coin des touches sont un
  repère technique de Keyman, pas les lettres de votre clavier.
</p>
<p>
  Le clavier visuel ne montre pas les capitales accentuées : <b>É È À Ç</b> s'obtiennent avec
  <kbd>Verr. Maj</kbd> allumé, sur les touches é, è, à et ç.
</p>

