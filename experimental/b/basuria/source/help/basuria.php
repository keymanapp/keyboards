<p>If vowel [u] appears after the "ch" "ts" "ș" "ż" consonant, then using letter "u" to spell the vowel. In Vủ-Hán accent, the vowel "u" is pronounced as [y] after "ch" "ts" "ș" "ż" consonant.</p>
