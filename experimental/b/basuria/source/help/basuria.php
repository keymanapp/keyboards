<p>在成都方言和大部分西南官話中，n往往變成l</p>
<p>In the Tsằng-Đu accent and most of Southwestern Mandarin, the "n" sound often becomes "l" sound.</p>
<p>在成都方言中，ch ts ș往往變成ț tx x</p>
<p>In the Tsằng-Đu accent, the "ch" "ts" and "ș" sound are often pronounced as "ț" "tx" "x" sound.</p>
<p>在成都方言中，z是ż的一種變體</p>
<p>In the Tsằng-Đu accent, the "z" sound is an variant of "ż" sound.</p>
<p>在成都方言中，聲母v往往读讀成[u]</p>
<p>In the Tsằng-Đu accent, the "v" consonant is often pronounced as [u]</p>
<p>在攔江話中，存在"b" "đ" "dz" "dzi" "di" "gh" "ğ"的濁音聲母</p>
<p>In the Làn-Giang accent, the voiced consonants "b" "đ" "dz" "dzi" "di" "gh" "ğ" exist.</p>
<p>在沒有濁音[b]和[d]的大多數官話口音中，仍然使用b和đ表示[p]和[t]</p>
<p>In the most of mandarin accent without voiced consonants [b] and [d], the letter b and đ are still applied to indicate [p] and [t]</p>

