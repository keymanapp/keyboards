<p>You can still type "î" specifically by <kbd>Alt</kbd> + <kbd>I</kbd>. In this way, the keyboard will remain the spelling with "î" letter.</p>
<p>You can type "ă" "â" "î" "ș" "ț" by long-pressing the "a" "i" "s" "t" key on the phone and pad as usual.</p>
