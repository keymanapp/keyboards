<p>
  Romania keyboard for Romanian language limba română.
</p>
<p>This is an innovative Romanian keyboard for phone and computer.</p>
<p>This keyboard can automatically remain the "î" letter in the beginning and the end of a word and transfer the "î" letter to "â" letter in the middle of a sentence.</p>
<p>You can type "î" key and get "â" automatically, depending on the content. </p>
<p>You can still type "â" individually as usual</p>
<p>You can still type "î" specifically by <kbd>Alt</kbd> + <kbd>I</kbd>. In this way, the keyboard will remain the spelling with "î" letter.</p>
<p>You can type "ă" "â" "î" "ș" "ț" by long-pressing the "a" "i" "s" "t" key on the phone and pad as usual.</p>
