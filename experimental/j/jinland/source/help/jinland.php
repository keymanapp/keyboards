<p>聲母y的發音遇到tr ch ș ż時候爲[ʅ]，遇到ț tx x z時候爲[ɿ]</p>
<p>When the vowel "y" appears after "tr" "ch" "ș," or "ż", it is pronounced as [ʅ]. After "ț" "tx" "x" or "z", it is pronounced as [ɿ].</p>
<p>如果â後面的入聲符號t可以省略，發音仍然是[əʔ]</p>
<p>If the entering tone mark "t" after "â" can be omitted, the pronunciation remains [əʔ].</p>
<p>在長治方言中，在汾陽話的o和uo音位變成ang,iang</p>
<p>In the Tràng-Chỵ dialect, the "o" and "uo" phonemes of Fân-Duò are pronounced as "ang" and "iang".</p>
<p>在晉語中in[ĩ]和iêng[iəŋ]屬於同一音位的不同變體</p>
<p>In Jin language, "in" [ĩ] and "iêng" [iəŋ] are different variants of the same phoneme.</p>
<p>在汾陽話中，ên的發音和an一樣，都是讀[ã]，在部分方言中，ên讀[ᴇ̃] [e] [ɛ]</p>
<p>In Fân-Duò accent, "ên" is pronounced the same as "an", both being realized as [ã]. In some dialects, "ên" is pronounced as [ᴇ̃], [e], or [ɛ].</p>
<p>在晉語中，[ou] [əu] 都是âu的變體</p>
<p>In Jin language, [ou] and [əu] are both variants of "âu".</p>
<p>在部分晉語方言中存在oây [uei]韻母，和ôi [ui]屬於同一個音位。</p>
<p>Some Jin dialects have the "oây" rhyme [uei], which belongs to the same phoneme as "ôi" [ui].</p>


