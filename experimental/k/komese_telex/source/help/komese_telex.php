<p>In Komese language, the "k" "kh" "h" "g" and "ğ" consonants are often palatalized to [tɕ] [tɕʰ] [ɕ] [dʑ] and [ʑ] when before "i" or "ư" vowels.</p>
<p>In nanchang dialect, the voiced consonants "đ" "g" "b" "dz" "đr" often don't exist because of devoicing process.</p>
<p>In nanchang dialect, the "ch" "x" "ș" "ż" and "đr" consonant have already merged to "ț" "țh" and "s"</p>
<p>The "k" consonant at the front can be replaced with "c" if it appears before the letter "a" "ă" "â" "o" "ô" "ơ" "u" or "ư".</p>


