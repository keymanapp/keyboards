<p>The "ö" letter in Kachin language often has merged into "u".</p>
<p>The "ŭ" letter in Kachin language often has merged into "ă".</p>
<p>During writing, glottal stop [ʔ] and tones are often not marked.</p>
<p>In modern days Kachin Language, the differenciation of vowel between letter "e" and letter "è" is minimizing and are often written as same vowel [e̞] combined with different tone in general.</p>
<p>In Kachin Language, the "ă" vowel usually deserves a low tone in a word or in a sentence.</p>

