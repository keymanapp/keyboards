<p>The vowel "o" is pronounced as "ă" in Taiwanese Accent, but still spelt as "o".</p>
<p>In some dialects, the [ɯ] "ư" vowel has already become to "i" or "u" sound.</p>
<p>The vowel "ô" is pronounced as [ou] in Teochew Accent</p>
<p>"iem" and "iep" phoneme in Taiwanese are pronounced as iam [iam] and iam [iap̚] in Teochew dialect</p>
<p>"iê" [iə̯] diphthong in Taiwanese are pronounced as "e" [e] in Teochew dialect</p>
<p>Vowel "ă" is used for loanwords and representing sounds</p>
<p>Diphthongs "ơe" and "ơu" exist in some Taiwanese and Amoy accent</p>
<p>Diphthongs "oi" "iô" and nasal vowel "ǫ̂" exist in Teochew accent</p>
<p>In south hokkienese language, the vowel "ê" [e] and the vowel "e" [ɛ] are mostly undifferentiated and interchangable</p>
<p>The "ong" and "oc" phoneme in Taiwanese can be pronounced as [ɔŋ] and [ɔk̚]</p>

