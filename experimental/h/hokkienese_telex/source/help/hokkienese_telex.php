<p>This Script of National Language for South Hokkienese Koc-Gứ-Dị is a writing system modified by Taiwanese POJ system and Teochew PUJ system.</p>
<p>This writing system absorbed features from Vietnamese, Polish, and Romanian script.</p>
<p>This script is easier for writing and reading comparing with POJ system</p>
